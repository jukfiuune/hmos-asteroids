#!/bin/bash
# Builds the vibrator pieces on the build PC (see vibrator_vdi.cpp, vibrator_hdi_publisher.cpp, richtap_server.c,
# haptic_ff.c):
#   hapticdrv.ko: the Richtek haptic driver from our kernel tree with hapticdrv-chip-init.patch (applied here if it
#     isn't yet): it waits for its config (firmware/haptic_config.bin) instead of trying once before HarmonyOS's root
#     is up, and it can be removed and loaded again. prep.sh loads it in place of M1's.
#   libasteroids_richtap.so (Bionic, run in /android by start-richtap.sh): Android's RichTap engine
#     (libaacvibrator) behind a socket, as LineageOS/EvoX's nothing-rt_ics HAL drives it.
#   libhdi_vibrator_impl.z.so: our vibrator VDI (the RichTap server; force feedback while it isn't up), over Huawei's
#     in /vendor/lib64.
#   native_vibrator_hdi_publisher: registers the donor's vibrator service, with that VDI below it, as
#     vibrator_interface_service (the asteroids_vibrator_hdi service).
#   asteroids_vibrate: a static test tool, "asteroids_vibrate <ms> | click | tick [amplitude]", through the server.
# The vibrator HDI 2.0 C++ headers are generated by hdi-gen from OpenHarmony's drivers_interface/vibrator, as for
# the motion and sensor services; the VDI interface is drivers_peripheral/vibrator's.
# Output: $WORK/out-vibrator/.
set -e
. "$(dirname "$0")/../../../build/env.sh"
HB=${HARMONY_BUILD:-$HOME/harmony-build}
M2=$WORK
N=$HB/ohos/sdk/native
S=$HB/ohos/src
O=$WORK/out-vibrator
L=$WORK/out-sensors/link
G=$O/gen
H=$(cd "$(dirname "$0")" && pwd)
mkdir -p $O
[ -f $L/libhdi.z.so ] || { echo "run sensors/build-sensors.sh first (donor link libraries)"; exit 1; }

HG=$S/drivers_hdf_core/framework/tools/hdi-gen/hdi-gen
I=$O/idl/ohos/hdi/vibrator
rm -rf $O/idl $G && mkdir -p $I $G
cp -r $S/drivers_interface/vibrator/v2_0 $I/
for f in v2_0/VibratorTypes.idl v2_0/IVibratorPlugCallback.idl v2_0/IVibratorInterface.idl; do
    $HG -s full -m ipc -l cpp -r ohos.hdi:$O/idl/ohos/hdi -c $I/$f -d $G
done

HDF=$S/drivers_hdf_core/interfaces/inner_api
INC="-I$G -I$G/vibrator -I$HDF/hdi -I$HDF/ipc -I$HDF/hdi/base -I$HDF/utils -I$HDF/osal/uhdf -I$HDF/core -I$HDF/host/uhdf
     -I$S/commonlibrary_c_utils/base/include -I$S/communication_ipc/interfaces/innerkits/ipc_core/include
     -I$S/communication_ipc/interfaces/innerkits/ipc_single/include -I$S/hiviewdfx_hilog/interfaces/native/innerkits/include"
CC="$N/llvm/bin/clang --target=aarch64-linux-ohos --sysroot=$N/sysroot -O2 -Wall -Wextra -fuse-ld=lld"
CXX="$N/llvm/bin/clang++ --target=aarch64-linux-ohos --sysroot=$N/sysroot -O2 -Wall -Wextra -std=c++17
     -fno-exceptions -fno-rtti -nostdlib++ -include $COMMON/include/platform_cpp_config.h -fuse-ld=lld"
BASE="$L/libutils.z.so $L/libc++.so $L/libipc_single.z.so $L/libipc_common.z.so -Wl,--allow-shlib-undefined"
K=$HB/src/kernel
git -C $K apply --check -R $H/hapticdrv-chip-init.patch 2>/dev/null || git -C $K apply $H/hapticdrv-chip-init.patch
(cd $K && ARCH=arm64 LLVM=1 LLVM_IAS=1 make -s O=../out/kernel M=drivers/misc/haptic -j10 modules)
$N/llvm/bin/llvm-strip --strip-debug -o $O/hapticdrv.ko $K/../out/kernel/drivers/misc/haptic/hapticdrv.ko
$CC -Wno-unused-command-line-argument -fPIC -c $H/haptic_ff.c -o $O/haptic_ff.o
$CC -Wno-unused-command-line-argument -fPIC -c $H/richtap_client.c -o $O/richtap_client.o
$CXX $INC -I$S/drivers_peripheral/vibrator/interfaces/v1_1 -I$H -Wno-unused-parameter -fPIC -fvisibility=hidden -shared \
    -Wl,-soname,libhdi_vibrator_impl.z.so $H/vibrator_vdi.cpp $O/haptic_ff.o $O/richtap_client.o $BASE $WORK/out-zink/link/libhilog.so -pthread \
    -o $O/libhdi_vibrator_impl.z.so
$CXX $INC $H/vibrator_hdi_publisher.cpp $L/libhdi.z.so $L/libhdi_base.z.so $BASE -ldl -pthread \
    -o $O/native_vibrator_hdi_publisher
$CC -static $H/richtap_client.c $H/asteroids_vibrate.c -o $O/asteroids_vibrate
# The server, for Android's Bionic and linker, as the audio and Bluetooth bridges (audio/build-audio.sh).
$N/llvm/bin/clang --target=aarch64-linux-android33 --sysroot=$N/sysroot -isystem $N/sysroot/usr/include/aarch64-linux-ohos \
    -fuse-ld=lld -fPIC -shared -nostdlib -D_GNU_SOURCE -mno-outline-atomics -O2 -Wall -Wextra -Wl,-z,defs \
    -L$WORK/bionic-link -I$H -Wl,-soname,libasteroids_richtap.so $H/richtap_server.c -lc -ldl \
    -o $O/libasteroids_richtap.so
ls -la $O/hapticdrv.ko $O/libasteroids_richtap.so $O/libhdi_vibrator_impl.z.so $O/native_vibrator_hdi_publisher $O/asteroids_vibrate
