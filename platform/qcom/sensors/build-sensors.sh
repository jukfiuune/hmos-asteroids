#!/bin/bash
# Builds sheng's sensor path (compat/sensors, copied to sensors/sheng) on the build PC:
#   libsensor_interface_service_3.1.z.so: sensor HDI 3.1 backed by the ADSP's sensor framework (SSC) through sheng's
#     QMI-over-QRTR client (accelerometer and gyro), loaded by
#   native_sensor_hdi_publisher: registers it as sensor_interface_service with the HDF service manager, through the
#     donor's own 3.0/3.1 stubs (/vendor/lib64/libsensor_driver.z.so), then sets bootevent.sheng_sensor_hdi.ready.
#   ssc_probe: reads both sensors directly, for testing (static); native_sensor_check: the same through HarmonyOS's
#     public sensor API (the asteroids_sensor_check service).
# The HDI 3.1 C++ headers are generated by hdi-gen (drivers_hdf_core/framework/tools/hdi-gen, built with
# "make CXXFLAGS=... -include cstdint" and third_party/bounds_checking_function linked in) from OpenHarmony's
# sensor 3.0 IDL (drivers_interface master, in $HARMONY_BUILD/ohos/src-new) and our 3.1 IDL (sensors/idl).
# Output: $WORK/out-sensors/.
set -e
. "$(dirname "$0")/../../../build/env.sh"
HB=${HARMONY_BUILD:-$HOME/harmony-build}
M2=$WORK
SH=$QCOM/sensors/sheng
N=$HB/ohos/sdk/native
S=$HB/ohos/src
DONOR=$HB/donor/pura70proplus-7.0.0.107/mnt
O=$WORK/out-sensors
L=$O/link
G=$O/gen
mkdir -p $L
for f in system/system/lib64/chipset-sdk-sp/{libc++.so,libutils.z.so,libhdi.z.so,libhdi_base.z.so,libbegetutil.z.so} \
         system/system/lib64/chipset-pub-sdk/{libipc_single.z.so,libipc_common.z.so}; do
    [ -f $L/$(basename $f) ] || sudo -n cat $DONOR/$f > $L/$(basename $f)
done

HG=$S/drivers_hdf_core/framework/tools/hdi-gen/hdi-gen
I=$O/idl/ohos/hdi/sensor
rm -rf $O/idl $G && mkdir -p $I $G
cp -r $HB/ohos/src-new/drivers_interface/sensor/v3_0 $QCOM/sensors/idl/v3_1 $I/
for f in v3_0/SensorTypes.idl v3_0/ISensorCallback.idl v3_0/ISensorPlugCallback.idl v3_0/ISensorInterface.idl \
         v3_1/ISensorInterface.idl; do
    $HG -s full -m ipc -l cpp -r ohos.hdi:$O/idl/ohos/hdi -c $I/$f -d $G
done

HDF=$S/drivers_hdf_core/interfaces/inner_api
INC="-I$SH -I$G -I$G/sensor -I$HDF/hdi -I$HDF/ipc -I$HDF/hdi/base -I$HDF/utils -I$HDF/osal/uhdf -I$HDF/core
     -I$S/commonlibrary_c_utils/base/include -I$S/communication_ipc/interfaces/innerkits/ipc_core/include
     -I$S/communication_ipc/interfaces/innerkits/ipc_single/include -I$S/hiviewdfx_hilog/interfaces/native/innerkits/include"
CC="$N/llvm/bin/clang --target=aarch64-linux-ohos --sysroot=$N/sysroot -O2 -Wall -Wextra -fuse-ld=lld"
CXX="$N/llvm/bin/clang++ --target=aarch64-linux-ohos --sysroot=$N/sysroot -O2 -Wall -Wextra -std=c++17
     -fno-exceptions -fno-rtti -nostdlib++ -include $COMMON/include/platform_cpp_config.h -fuse-ld=lld"
QRTR=$QCOM/audio/pd-mapper
SSC="$SH/ssc_backend.c $QRTR/qrtr.c $QRTR/logging.c"
$CC -std=c11 -D_GNU_SOURCE -fPIC -pthread -I$QRTR -c $SH/ssc_backend.c -o $O/ssc_backend.o
$CC -std=c11 -D_GNU_SOURCE -fPIC -pthread -I$QRTR -c $QRTR/qrtr.c -o $O/qrtr.o
$CC -std=c11 -D_GNU_SOURCE -fPIC -pthread -I$QRTR -c $QRTR/logging.c -o $O/logging.o
$CC -std=c11 -D_GNU_SOURCE -fPIC -pthread -c $SH/ssc_time.c -o $O/ssc_time.o
BASE="$L/libutils.z.so $L/libc++.so $L/libipc_single.z.so $L/libipc_common.z.so -Wl,--allow-shlib-undefined"
$CXX $INC -fPIC -fvisibility=hidden -shared -Wl,-soname,libsensor_interface_service_3.1.z.so \
    $SH/sensor_interface_service.cpp $O/ssc_backend.o $O/qrtr.o $O/logging.o $O/ssc_time.o $BASE -ldl -pthread \
    -o $O/libsensor_interface_service_3.1.z.so
$CXX $INC $SH/sensor_hdi_publisher.cpp $L/libhdi.z.so $L/libhdi_base.z.so $L/libbegetutil.z.so $BASE -ldl -pthread \
    -o $O/native_sensor_hdi_publisher
$CC -std=c11 -D_GNU_SOURCE -pthread -I$QRTR -static $QCOM/sensors/ssc_probe.c $SSC -o $O/ssc_probe
$CC $QCOM/sensors/native_sensor_check.c -lohsensor -o $O/native_sensor_check
ls -l $O/libsensor_interface_service_3.1.z.so $O/native_sensor_hdi_publisher $O/ssc_probe
